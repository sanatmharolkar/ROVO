# --- Markdown of the competency-question files to HTML -----------------------

def inline(text):
    text = html.escape(text, quote=False)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    text = re.sub(r"\*([^*]+)\*", r"<em>\1</em>", text)
    return text


def table(rows):
    head, body = rows[0], rows[2:]
    out = ["<table class=\"cq\">", "<thead><tr>" + "".join(f"<th>{inline(c)}</th>" for c in head) + "</tr></thead>", "<tbody>"]
    for row in body:
        cells = [inline(c) for c in row]
        first = cells[0]
        if re.fullmatch(r"(SA|LK)-\d\d", first):
            cells[0] = f'<span id="{first}">{first}</span>'
        out.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    out += ["</tbody>", "</table>"]
    return "\n".join(out)


def read_catalogue(path):
    """Return (questions_html, references_html) of one competency-question file."""
    lines = path.read_text(encoding="utf-8").split("\n")
    parts = {"questions": [], "references": []}
    part = "questions"
    i = 1  # skip the title
    while i < len(lines):
        line = lines[i]
        if line.startswith("## References"):
            part = "references"
        elif line.startswith("## "):
            parts[part].append(f"<h4>{inline(line[3:])}</h4>")
        elif line.startswith("### "):
            parts[part].append(f"<h4>{inline(line[4:])}</h4>")
        elif line.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append([c.strip() for c in lines[i].strip().strip("|").split("|")])
                i += 1
            parts[part].append(table(rows))
            continue
        elif line.strip():
            parts[part].append(f"<p>{inline(line)}</p>")
        i += 1
    return "\n".join(parts["questions"]), "\n".join(parts["references"])


# --- Definitions from the Turtle file ----------------------------------------

def definitions(ttl):
    """skos:definition texts of a Turtle file, whitespace-normalised."""
    text = ttl.read_text(encoding="utf-8")
    return {norm(m.group(1).replace('\\"', '"')) for m in re.finditer(r'skos:definition\s+"((?:[^"\\]|\\.)*)"@en', text)}


def norm(text):
    return re.sub(r"\s+", " ", html.unescape(text)).strip()


COMMENT = re.compile(r'<div class="comment">\s*<span class="markdown">(.*?)</span>\s*</div>', re.S)


def definitions_first(page, defs):
    """In each entity, show the definition before the notes and label both."""
    def fix(match):
        blocks = COMMENT.findall(match.group(0))
        is_def = [norm(b) in defs for b in blocks]
        if len(blocks) < 2 or sum(is_def) != 1:
            return match.group(0)
        definition = blocks[is_def.index(True)]
        notes = [b for b, d in zip(blocks, is_def) if not d]
        new = [f'<div class="comment"><p><strong>Definition:</strong></p>\n<span class="markdown">{definition}</span>\n</div>']
        new += [f'<div class="comment"><p><strong>Note:</strong></p>\n<span class="markdown">{n}</span>\n</div>' for n in notes]
        return "\n  ".join(new)
    run = re.compile(r'(?:<div class="comment">\s*<span class="markdown">.*?</span>\s*</div>\s*){2,}', re.S)
    return run.sub(fix, page)


# --- Build -------------------------------------------------------------------

STYLE = """<style>
table.cq { border-collapse: collapse; margin: 0.5em 0 1.5em 0; width: 100%; }
table.cq th, table.cq td { border: 1px solid #bbb; padding: 4px 8px; vertical-align: top; text-align: left; }
table.cq td:first-child { white-space: nowrap; }
</style>
</head>"""


def replace_once(page, old, new, what):
    if page.count(old) != 1:
        sys.exit(f"{what}: expected one match in the WIDOCO page, found {page.count(old)}")
    return page.replace(old, new)


def markdown_span(text):
    return '<span class="markdown">\n' + html.escape(text.strip(), quote=False) + "</span>"


def build(name, mod):
    out = DOCS / name
    with tempfile.TemporaryDirectory() as tmp:
        conf = Path(tmp) / "widoco.properties"
        props = {
            "ontologyTitle": mod["title"],
            "ontologyName": mod["title"],
            "ontologyPrefix": mod["prefix"],
            "ontologyNamespaceURI": mod["iri"] + "#",
            "latestVersionURI": mod["iri"],
            "ontologyRevisionNumber": "1.0",
            "dateModified": "2026-11-14",
            "authors": AUTHOR,
            "authorsInstitution": INSTITUTION,
            "licenseURI": "http://www.apache.org/licenses/LICENSE-2.0",
            "licenseName": "Apache License 2.0",
            "citeAs": f"{AUTHOR}. {mod['title']}. Version 1.0, 2026. {mod['iri']}",
            "status": "Version 1.0",
            "importedOntologyNames": "; ".join(n for n, _ in mod["imports"]),
            "importedOntologyURIs": "; ".join(u for _, u in mod["imports"]),
            "RDFXMLSerialization": "ontology.owl",
            "TurtleSerialization": "ontology.ttl",
            "NTSerialization": "ontology.nt",
            "JSONLDSerialization": "ontology.jsonld",
        }
        conf.write_text("".join(f"{k}={v}\n" for k, v in props.items()), encoding="utf-8")
        work = Path(tmp) / "out"
        cmd = WIDOCO + ["-ontFile", str(ROOT / mod["file"]), "-outFolder", str(work), "-confFile", str(conf),
                        "-rewriteAll", "-webVowl", "-uniteSections"]
        run = subprocess.run(cmd, capture_output=True, text=True)
        if run.returncode != 0 or not (work / "index-en.html").exists():
            sys.exit(f"WIDOCO failed for {name}:\n{run.stdout[-3000:]}\n{run.stderr[-3000:]}")
        if out.exists():
            shutil.rmtree(out)
        shutil.copytree(work, out)

    (out / "readme.md").unlink(missing_ok=True)  # WIDOCO's note about its own output
    page_path = out / "index-en.html"
    page = page_path.read_text(encoding="utf-8")

    page = replace_once(page, "</head>", STYLE, "head")
    page = replace_once(page, "<dt>Issued on:</dt>\n<dd>Date issued</dd>\n", "", "issue date")
    page = replace_once(page, '"datePublished":"Date issued", ', "", "issue date in the page metadata")
    page = replace_once(
        page,
        '<span class="markdown">\nThis is a placeholder text for the abstract. The abstract should contain a couple of sentences summarizing the ontology and its purpose.</span>',
        markdown_span(mod["abstract"]), "abstract")
    page = replace_once(
        page,
        '<span class="markdown">\nThis is a place holder text for the introduction. The introduction should briefly describe the ontology, its motivation, state of the art and goals.</span>',
        markdown_span(mod["intro"]), "introduction")

    questions = references = ""
    if mod["cq"]:
        questions, references = read_catalogue(ROOT / "competency-questions" / mod["cq"])
        questions = ('<h3 id="cq" class="list">Competency questions</h3>\n'
                     "<p>The module answers the competency questions below. The notes of the terms name the questions "
                     "each term serves, and the keys in the Sources column are resolved under "
                     '<a href="#ref">References</a>.</p>\n' + questions)

    # Description: the text given here, then the questions.
    start = page.index('<div id="description">')
    end = page.index("</div>", start)
    section = page[start:end]
    section = re.sub(r'<span class="markdown">.*?</span>', lambda _: markdown_span(mod["description"]), section, count=1, flags=re.S)
    page = page[:start] + section + ("\n" + questions + "\n" if questions else "") + page[end:]

    placeholder = '<span class="markdown">\nAdd your references here. It is recommended to have them as a list.</span>'
    if references:
        page = replace_once(page, placeholder, references, "references")
    else:
        page = replace_once(page, placeholder,
                            "<p>The sources of each alignment are the ontologies named in the term declarations "
                            "(<code>rdfs:isDefinedBy</code>).</p>", "references")

    page = definitions_first(page, definitions(ROOT / mod["file"]))
    page_path.write_text(page, encoding="utf-8")
    shutil.copyfile(page_path, out / "index.html")  # so that docs/<module>/ opens the page
    print(f"docs/{name}/  written")


def main():
    for name, mod in MODULES.items():
        build(name, mod)


if __name__ == "__main__":
    main()
